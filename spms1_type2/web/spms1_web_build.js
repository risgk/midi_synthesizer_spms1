// Builds SPMS-1 Web: "../spms1_web_synth.js" (loaded by "../spms1_editor.html").
// Requirements: Emscripten (emcc in PATH, e.g. after "emsdk_env"; wasm-opt of its Binaryen is used too) and Node.js (included in emsdk).
// Usage (in this folder): node spms1_web_build.js

"use strict";

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execSync } = require("child_process");

const HERE   = __dirname;
const ROOT   = path.join(HERE, "..");
const SKETCH = path.join(ROOT, "spms1");
const OUTPUT = path.join(ROOT, "spms1_web_synth.js");

// The version is the same as SPMS-1 (type-2) (the title of README.md)
const readme = fs.readFileSync(path.join(ROOT, "README.md"), "utf8");
const versionMatch = readme.match(/^MIDI Synthesizer SPMS-1 \(type-2\) (v[0-9]+\.[0-9]+\.[0-9]+)/m);
if (!versionMatch) {
  throw new Error("The version is not found in the title of README.md");
}
const version = "SPMS-1 (type-2) Web " + versionMatch[1];

const run = (command) => {
  console.log(command);
  execSync(command, { stdio: "inherit" });
};
const q = (s) => JSON.stringify(s);

// spms1_main.c (the Spinel output the sketch runs) and the Spinel runtime of the sketch, not modified
const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "spms1-web-"));
const linkedPath = path.join(workDir, "spms1-web-linked.wasm");
const wasmPath = path.join(workDir, "spms1-web.wasm");
const runtimeSources = fs.readdirSync(SKETCH)
  .filter((f) => /^(sp|re)_.*\.c$/.test(f))
  .sort()
  .map((f) => path.join(SKETCH, f));
const sources = [
  path.join(HERE, "spms1_web_main.c"),
  path.join(SKETCH, "spms1_main.c"),
  ...runtimeSources,
];
run([
  "emcc", "-O3", "-w",
  "-include", q(path.join(HERE, "spms1_web_compat.h")), "-I" + q(SKETCH),
  "-sSTANDALONE_WASM", "--no-entry", "-sFILESYSTEM=0",
  "-sINITIAL_MEMORY=4MB", "-sSTACK_SIZE=256KB", "-sALLOW_MEMORY_GROWTH=1",
  ...sources.map(q),
  "-o", q(linkedPath),
].join(" "));

// Asyncify lets spms1_web_yield (imported from the AudioWorkletProcessor) unwind Spms1_main,
// which never returns, once a block is filled, and rewind it for the next block. Only the calls
// that reach spms1_web_yield are instrumented; the runtime makes no indirect calls into it.
const binaryenRoot = execSync("em-config BINARYEN_ROOT", { encoding: "utf8" }).trim();
run([
  q(path.join(binaryenRoot, "bin", "wasm-opt")), "-O3", "--asyncify",
  // The WebAssembly features that emcc enables by default
  "--enable-bulk-memory", "--enable-bulk-memory-opt", "--enable-nontrapping-float-to-int",
  "--enable-sign-ext", "--enable-mutable-globals", "--enable-multivalue", "--enable-reference-types",
  "--pass-arg=asyncify-imports@env.spms1_web_yield",
  "--pass-arg=asyncify-ignore-indirect",
  q(linkedPath), "-o", q(wasmPath),
].join(" "));

const wasm = fs.readFileSync(wasmPath);
fs.rmSync(workDir, { recursive: true, force: true });

// Embeds the version, the WebAssembly binary (Base64), and the AudioWorkletProcessor (a string) in the main part
const processor = fs.readFileSync(path.join(HERE, "spms1_web_synth_processor.js"), "utf8");
const main = fs.readFileSync(path.join(HERE, "spms1_web_synth_main.js"), "utf8");
const replace = (text, name, value) => {
  const placeholder = "/*@" + name + "@*/\"\"";
  if (!text.includes(placeholder)) {
    throw new Error(placeholder + " is not found in spms1_web_synth_main.js");
  }
  return text.replace(placeholder, () => JSON.stringify(value));
};
let output = main;
output = replace(output, "SPMS1_WEB_VERSION", version);
output = replace(output, "WASM_BASE64", wasm.toString("base64"));
output = replace(output, "PROCESSOR_SOURCE", processor);
output = "// " + version + " (generated by \"web/spms1_web_build.js\", do not edit)\n" + output;

fs.writeFileSync(OUTPUT, output);
console.log("Generated: " + OUTPUT + " (" + output.length + " bytes; WebAssembly: " + wasm.length + " bytes)");
